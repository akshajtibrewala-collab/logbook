// LEGACY / LOCAL-ONLY TOOL — do not use this for a production import.
//
// The aircraft find-or-create step this script used to be the only place that did now lives in the app
// itself (POST /api/flights/bulk, for role='passenger' rows — see findOrCreateAircraftByTail in
// server/src/routes/flights.js), so the app's own Import screen (ImportExport.jsx) is the correct, safe way
// to import passenger flights anywhere, including production. This script is kept only as a local
// dry-run/reporting convenience (its console summary of ready/duplicate/error and new-vs-matched aircraft
// counts) and must never be pointed at a production API_BASE.
//
// Loads server/imports/passenger-flights-import.csv (generated by convert-flightdiary-import.js) into a
// running local API — the exact same client/src/lib/csv.js parseImport() the Import screen uses, then
// POST /api/flights/bulk, the exact same route ImportExport.jsx's "Import" button calls, which now does its
// own aircraft find-or-create identically to what this script does below.
//
// Default is a dry run: parses, matches against what's already in the database, and reports — no writes
// anywhere. Idempotent: re-running (even with --load) against unchanged data creates nothing new, because
// it relies on parseImport's own duplicate detection (date + departure + arrival + flight_number +
// tail_number, against every flight already in the database) exactly as the Import screen does.
//
//   node server/scripts/import-passenger-flights.js [csv-path]              dry run (default)
//   node server/scripts/import-passenger-flights.js [csv-path] --load       actually creates aircraft + flights
//
// Talks only to http://localhost:3001 (or $API_BASE) — never Turso, never production. Requires the local
// dev server to be running (npm run dev -w server). Never set API_BASE to a production URL.
import { readFileSync } from 'node:fs';
import { parseDelimited, parseImport } from '../../client/src/lib/csv.js';

const API_BASE = process.env.API_BASE || 'http://localhost:3001/api';
const args = process.argv.slice(2);
const load = args.includes('--load');
const csvPath = args.find((a) => !a.startsWith('--')) || 'server/imports/passenger-flights-import.csv';

async function api(method, path, body) {
  const res = await fetch(`${API_BASE}${path}`, {
    method, headers: body ? { 'content-type': 'application/json' } : undefined, body: body ? JSON.stringify(body) : undefined,
  });
  if (!res.ok) throw new Error(`${method} ${path} -> ${res.status}: ${await res.text()}`);
  return res.status === 204 ? null : res.json();
}

const normTail = (t) => (t ? String(t).trim().toUpperCase() : null);

async function main() {
  const csvText = readFileSync(csvPath, 'utf8');
  const existingFlights = await api('GET', '/flights');
  const existingGround = await api('GET', '/costs/ground-sessions');
  const { rows, error } = parseImport(csvText, existingFlights, existingGround);
  if (error) throw new Error(error);

  const ready = rows.filter((r) => r.status === 'ready');
  const duplicate = rows.filter((r) => r.status === 'duplicate');
  const failed = rows.filter((r) => r.status === 'error');
  const totalHours = Math.round(ready.reduce((s, r) => s + (Number(r.flight.total_time) || 0), 0) * 100) / 100;

  // Aircraft impact: only rows with a tail_number ever touch the aircraft table; rows without one keep
  // aircraft_type as free text only, same as any other flight without a linked aircraft.
  const existingAircraft = await api('GET', '/aircraft?archived=1');
  const existingTailSet = new Set(existingAircraft.map((a) => normTail(a.tail_number)).filter(Boolean));
  const tailsInImport = new Set(ready.map((r) => normTail(r.flight.tail_number)).filter(Boolean));
  const newAircraftTails = [...tailsInImport].filter((t) => !existingTailSet.has(t));
  const matchedAircraftTails = [...tailsInImport].filter((t) => existingTailSet.has(t));
  const noRegistrationCount = ready.filter((r) => !r.flight.tail_number).length;

  console.log(`Parsed ${rows.length} rows from ${csvPath}`);
  console.log(`  ready:      ${ready.length}`);
  console.log(`  duplicate:  ${duplicate.length} (already in the database — re-running is a no-op for these)`);
  console.log(`  error:      ${failed.length}`);
  for (const f of failed) console.log(`    row ${f.row}: ${JSON.stringify(f.errors)}`);
  console.log(`Total hours across ready rows: ${totalHours}`);
  console.log(`Aircraft: ${newAircraftTails.length} new (${newAircraftTails.join(', ') || '—'}), ${matchedAircraftTails.length} matched an existing aircraft, ${noRegistrationCount} rows with no registration (type text only, no aircraft record)`);

  if (!load) {
    console.log('\nDry run only — nothing written. Re-run with --load to actually import.');
    return;
  }
  if (!ready.length) {
    console.log('\nNothing ready to load.');
    return;
  }

  // Aircraft first (only for tail numbers not already present), so their ids are available to link.
  const aircraftIdByTail = new Map(existingAircraft.map((a) => [normTail(a.tail_number), a.id]));
  for (const tail of newAircraftTails) {
    const sample = ready.find((r) => normTail(r.flight.tail_number) === tail).flight;
    const created = await api('POST', '/aircraft', { tail_number: tail, model: sample.aircraft_type || '' });
    aircraftIdByTail.set(tail, created.id);
  }
  for (const r of ready) {
    const tail = normTail(r.flight.tail_number);
    if (tail) r.flight.aircraft_id = aircraftIdByTail.get(tail) ?? null;
  }

  const { inserted, failed: bulkFailed } = await api('POST', '/flights/bulk', { flights: ready.map((r) => r.flight) });
  console.log(`\nLoaded: ${inserted} flight(s) inserted, ${bulkFailed.length} rejected by the server.`);
  for (const f of bulkFailed) console.log(`  index ${f.index}: ${JSON.stringify(f.errors)}`);
}

await main();
